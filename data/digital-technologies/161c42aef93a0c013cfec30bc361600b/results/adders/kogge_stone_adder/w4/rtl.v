module adder_top(input [3:0] a, b, input cin, output [3:0] sum, output cout);
  wire [3:0] p0 = a ^ b;
  wire [3:0] g0 = a & b;
  wire [3:0] p1;
  wire [3:0] g1;
  assign p1[0] = p0[0];
  assign g1[0] = g0[0];
  assign p1[1] = p0[1] & p0[0];
  assign g1[1] = g0[1] | (p0[1] & g0[0]);
  assign p1[2] = p0[2] & p0[1];
  assign g1[2] = g0[2] | (p0[2] & g0[1]);
  assign p1[3] = p0[3] & p0[2];
  assign g1[3] = g0[3] | (p0[3] & g0[2]);
  wire [3:0] p2;
  wire [3:0] g2;
  assign p2[0] = p1[0];
  assign g2[0] = g1[0];
  assign p2[1] = p1[1];
  assign g2[1] = g1[1];
  assign p2[2] = p1[2] & p1[0];
  assign g2[2] = g1[2] | (p1[2] & g1[0]);
  assign p2[3] = p1[3] & p1[1];
  assign g2[3] = g1[3] | (p1[3] & g1[1]);
  wire [4:0] carry;
  assign carry[0] = cin;
  assign carry[1] = g2[0] | (p2[0] & cin);
  assign carry[2] = g2[1] | (p2[1] & cin);
  assign carry[3] = g2[2] | (p2[2] & cin);
  assign carry[4] = g2[3] | (p2[3] & cin);
  assign sum = p0 ^ carry[3:0];
  assign cout = carry[4];
endmodule
