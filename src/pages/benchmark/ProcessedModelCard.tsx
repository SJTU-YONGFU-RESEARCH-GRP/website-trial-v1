/* ==================================================================
 *  ProcessedModelCard (goal.md §13)
 *  Model code preview, copy, download, and source model diff.
 * ================================================================== */

import { useState, useCallback, useMemo } from "react";
import type { WorkflowScenario } from "../../compat/spiceWorkflow/contracts";
import { DataOriginBadge } from "./shared/DataOriginBadge";

interface Props { scenario: WorkflowScenario; modelId: string | null; baselineModelId?: string | null }

export function ProcessedModelCard({ scenario, modelId, baselineModelId }: Props) {
  const model = modelId ? scenario.models[modelId] : null;
  const baseline = baselineModelId ? scenario.models[baselineModelId] : null;
  const [expanded, setExpanded] = useState(false);
  const [diffMode, setDiffMode] = useState<"preview" | "diff">("preview");

  const handleCopy = useCallback(() => {
    if (model?.content) navigator.clipboard.writeText(model.content).catch(() => {});
  }, [model?.content]);

  const handleDownload = useCallback(() => {
    if (!model?.content) return;
    const blob = new Blob([model.content], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url; a.download = model.filename; a.click();
    URL.revokeObjectURL(url);
  }, [model]);

  // Parameter-level diff
  const paramDiff = useMemo(() => {
    if (!baseline?.content || !model?.content) return null;
    const baseParams = extractParams(baseline.content);
    const candParams = extractParams(model.content);
    const allKeys = new Set([...Object.keys(baseParams), ...Object.keys(candParams)]);
    const rows: { param: string; baseline: string; candidate: string; changed: boolean }[] = [];
    for (const k of allKeys) {
      rows.push({
        param: k,
        baseline: baseParams[k] ?? "—",
        candidate: candParams[k] ?? "—",
        changed: baseParams[k] !== candParams[k],
      });
    }
    return rows.sort((a, b) => a.param.localeCompare(b.param));
  }, [baseline?.content, model?.content]);

  if (!model) {
    return (
      <div className="chart-card" id="processed-model" style={{ marginTop: "0.85rem" }}>
        <h2>Processed Model Output</h2>
        <p className="hint">Select a model from the lineage to preview, copy, or download.</p>
      </div>
    );
  }

  return (
    <div className="chart-card" id="processed-model" style={{ marginTop: "0.85rem" }}>
      <h2>Processed Model Output</h2>

      <div className="bmw-badge-row">
        <span className="tr-badge tr-badge--completed">{model.dialect}</span>
        <span className="tr-badge tr-badge--completed">{model.variant}</span>
        <span className="tr-badge tr-badge--completed">{model.modelNames.join(", ")}</span>
        <DataOriginBadge origin={model.provenance.origin} />
        {model.temporary && <span className="tr-badge tr-badge--partial">temporary</span>}
      </div>

      <div className="bmw-model-meta">
        <div><strong>Filename:</strong> {model.filename}</div>
        <div><strong>Parameters:</strong> {model.parameterCount ?? "Unknown"}</div>
        <div><strong>Size:</strong> {model.byteSize !== null ? `${model.byteSize} B` : "Unknown"}</div>
        <div><strong>Generated by:</strong> {model.generatedBy}</div>
        <div><strong>Persistent:</strong> {model.persistent ? "Yes" : "No"}</div>
        <div><strong>Checksum:</strong> {model.checksum ?? "N/A"}</div>
      </div>

      {/* View toggle */}
      <div className="bmw-btn-row">
        <button className="benchmark-btn" onClick={() => setExpanded(!expanded)}>
          {expanded ? "Hide model" : "Show model code"}
        </button>
        {baseline && (
          <button className="benchmark-btn" onClick={() => setDiffMode(diffMode === "preview" ? "diff" : "preview")}>
            {diffMode === "preview" ? "Show parameter diff" : "Show code preview"}
          </button>
        )}
        <button className="benchmark-btn" onClick={handleCopy} disabled={!model.content}>Copy model</button>
        <button className="benchmark-btn" onClick={handleDownload} disabled={!model.content}>Download model</button>
      </div>

      {/* Content area */}
      {expanded && (
        <div style={{ marginTop: "0.5rem" }}>
          {diffMode === "preview" && model.content && (
            <pre className="bmw-code-preview">{model.content}</pre>
          )}

          {diffMode === "diff" && paramDiff && (
            <div className="bmw-diff-table-wrap">
              <p style={{ fontSize: "0.72rem", fontWeight: 600, marginBottom: "0.35rem" }}>
                Parameter Diff: {baseline?.displayName ?? "baseline"} → {model.displayName}
              </p>
              <table className="bmw-diff-table">
                <thead>
                  <tr>
                    <th>Parameter</th><th>Baseline</th><th>Candidate</th><th>Status</th>
                  </tr>
                </thead>
                <tbody>
                  {paramDiff.map((row) => (
                    <tr key={row.param} className={row.changed ? "bmw-diff-changed" : ""}>
                      <td className="bmw-diff-param">{row.param}</td>
                      <td className="bmw-diff-mono">{row.baseline}</td>
                      <td className="bmw-diff-mono">{row.candidate}</td>
                      <td>
                        {row.changed
                          ? <span className="tr-badge tr-badge--failed" style={{ fontSize: "0.6rem" }}>changed</span>
                          : <span style={{ fontSize: "0.62rem", color: "var(--muted, #aaa)" }}>unchanged</span>}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {diffMode === "diff" && !paramDiff && (
            <p className="hint">No baseline model available for comparison.</p>
          )}
        </div>
      )}
    </div>
  );
}

/* ─── Helpers ─── */

function extractParams(content: string): Record<string, string> {
  const params: Record<string, string> = {};
  const lines = content.split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed.startsWith("+ ") && !trimmed.startsWith("+")) continue;
    // Match "+ key=value" or "+ key = value"
    const parts = trimmed.replace(/^\+/, "").trim().split(/\s+/);
    for (const part of parts) {
      const eq = part.indexOf("=");
      if (eq > 0) {
        const key = part.slice(0, eq).trim();
        const val = part.slice(eq + 1).trim();
        params[key] = val;
      }
    }
  }
  // Also match .model line params
  const modelLine = lines.find((l) => l.trim().startsWith(".model"));
  if (modelLine) {
    const afterModel = modelLine.replace(/\.model\s+\w+\s+\w+\s*/, "");
    const parts = afterModel.split(/\s+/);
    for (const part of parts) {
      const eq = part.indexOf("=");
      if (eq > 0) {
        const key = part.slice(0, eq).trim();
        const val = part.slice(eq + 1).trim();
        params[key] = val;
      }
    }
  }
  return params;
}
