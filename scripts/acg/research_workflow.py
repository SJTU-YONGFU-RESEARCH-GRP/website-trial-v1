def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--request", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--artifacts-root", type=Path)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--stage", choices=("comparison", "search", "report"))
    args = parser.parse_args(argv)
    if args.stage:
        import unified_workflow
        return unified_workflow.main(["--request", str(args.request), "--output", str(args.output),
                                      "--artifacts-root", str(args.artifacts_root), "--stage", args.stage])
    try:
        if args.self_test:
            import unified_workflow
            proof = self_test()
            proof["unifiedHelper"] = unified_workflow.self_test()
            print(json.dumps(proof, sort_keys=True)); return 0
        if not all((args.request,args.output,args.artifacts_root)):
            raise ValueError("request/output/artifacts-root are required")
        result = run(args.request,args.output,args.artifacts_root)
        print(json.dumps({"status":result["status"],"schemaVersion":VERSION,"nativeReturnCode":result["nativeReturnCode"]}))
        # Native partial results are reviewable outcomes. Preserve native exit code in summary.
        return 0
    except (ValueError,OSError,KeyError,TypeError,json.JSONDecodeError) as exc:
        print(json.dumps({"status":"error","message":str(exc)}), file=sys.stderr)
        return 2


