def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read_json(path: Path) -> Any:
    def invalid(value: str):
        raise ValueError(f"non-finite JSON number: {value}")
    return json.loads(path.read_text(encoding="utf-8"), parse_constant=invalid)


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


def confined(root: Path, relative: str, *, directory: bool = False) -> Path:
    if not isinstance(relative, str) or not relative or "\\" in relative:
        raise ValueError("input must be a nonempty job-relative POSIX path")
    parts = PurePosixPath(relative)
    if parts.is_absolute() or any(p in {"..", "."} for p in parts.parts):
        raise ValueError(f"unconfined input: {relative}")
    candidate = root / relative
    for parent in [candidate, *candidate.parents]:
        if parent == root.parent:
            break
        if parent.is_symlink():
            raise ValueError(f"symlink input rejected: {relative}")
    candidate = candidate.resolve()
    if not candidate.is_relative_to(root):
        raise ValueError(f"input outside job: {relative}")
    if not (candidate.is_dir() if directory else candidate.is_file()):
        raise ValueError(f"input missing: {relative}")
    return candidate


def safe_tree(root: Path) -> list[Path]:
    result = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"symlink in artifact tree: {path.relative_to(root)}")
        if path.is_file():
            if not path.resolve().is_relative_to(root.resolve()):
                raise ValueError("artifact escapes tree")
            result.append(path)
        elif not path.is_dir():
            raise ValueError("special file in artifact tree")
    return result


def tag(value: Any) -> str:
    if not isinstance(value, str) or not TAG.fullmatch(value):
        raise ValueError("invalid native identifier")
    return value


def positive(value: Any, label: str, maximum: int) -> int:
    if type(value) is not int or not 1 <= value <= maximum:
        raise ValueError(f"{label} must be an integer in 1..{maximum}")
    return value


def integer_list(value: Any, label: str, minimum: int, maximum: int, *, ordered=False) -> list[int]:
    if not isinstance(value, list) or not value or any(type(x) is not int or not minimum <= x <= maximum for x in value):
        raise ValueError(f"invalid {label}")
    if len(set(value)) != len(value) or ordered and value != sorted(value):
        raise ValueError(f"{label} must be unique" + (" and ascending" if ordered else ""))
    return value


def validate_request(request: dict) -> dict:
    if not isinstance(request, dict) or request.get("schemaVersion") != REQUEST_VERSION:
        raise ValueError("unsupported research request schema")
    operation, engine = request.get("operation"), request.get("engine")
    if operation not in OPERATIONS or engine not in {"cmos", "mr"}:
        raise ValueError("unsupported native workflow/engine")
    params = request.get("parameters", {})
    if not isinstance(params, dict):
        raise ValueError("parameters must be an object")
    p = dict(params)
    if operation in {"algorithm-matrix", "algorithm-report"}:
        p["maxCols"] = positive(p.get("maxCols", 8), "maxCols", 32)
        if p["maxCols"] < 4:
            raise ValueError("maxCols must be >=4")
    if operation == "algorithm-matrix":
        p["cells"] = [tag(x) for x in p.get("cells", ["inv_x1"])]
        if not p["cells"] or len(set(p["cells"])) != len(p["cells"]) or any(x not in CELLS for x in p["cells"]):
            raise ValueError("matrix requires unique native benchmark cells")
        p["algorithms"] = [tag(x) for x in p.get("algorithms", ["dp", "sa"])]
        if not p["algorithms"] or len(set(p["algorithms"])) != len(p["algorithms"]):
            raise ValueError("algorithms must be nonempty and unique")
        p["trials"] = positive(p.get("trials", 1), "trials", 10)
        p["threads"] = positive(p.get("threads", 1), "threads", 4)
        p["rowCounts"] = integer_list(p.get("rowCounts", [1, 2, 3] if engine == "mr" else [1]), "rowCounts", 1, 4)
        if engine == "cmos" and p["rowCounts"] != [1]:
            raise ValueError("CMOS native runner has no row-count control")
        count = len(p["cells"]) * len(p["algorithms"]) * len(p["rowCounts"]) * p["trials"]
        if count > 1000:
            raise ValueError("matrix exceeds service 1000-run limit")
    elif operation == "known-feasible":
        if engine != "mr":
            raise ValueError("native known-feasible workflow requires MR GF180")
        p["cells"] = [tag(x) for x in p.get("cells", [])]
        if not 1 <= len(p["cells"]) <= 15 or len(set(p["cells"])) != len(p["cells"]):
            raise ValueError("corpus requires 1..15 unique cells")
        p["numRows"] = positive(p.get("numRows", 1), "numRows", 3)
        p["tracks"] = integer_list(p.get("tracks", [9, 12, 16]), "tracks", 5, 16, ordered=True)
        if p["numRows"] == 1 and any(x not in {9, 12, 16} for x in p["tracks"]):
            raise ValueError("single-row GF180 heights are 9,12,16")
        p["extraCpp"] = integer_list(p.get("extraCpp", [0, 2, 4, 8, 16]), "extraCpp", 0, 16, ordered=True)
        for name, default, maximum in [("maxAttempts",30,100),("totalTimeoutSeconds",3600,86400),("attemptTimeoutSeconds",900,3600)]:
            p[name] = positive(p.get(name, default), name, maximum)
    allowed = ({"maxCols", "sourceResultId"} if operation == "algorithm-report" else
               {"cells","algorithms","trials","threads","rowCounts","maxCols"} if operation == "algorithm-matrix" else
               {"cells","numRows","tracks","extraCpp","maxAttempts","totalTimeoutSeconds","attemptTimeoutSeconds","resumeResultId"})
    if set(params) - allowed:
        raise ValueError("unsupported workflow parameter: " + ",".join(sorted(set(params) - allowed)))
    return p


def load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ValueError("native script import failed")
    module = importlib.util.module_from_spec(spec)
    old = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        sys.modules[name] = module
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = old
    return module


class ObservedSubprocess:
    """Record exact captured child streams without changing native subprocess semantics."""
    TimeoutExpired = subprocess.TimeoutExpired
    def __init__(self, native_root: Path):
        self.root = native_root.resolve()
    def __getattr__(self, name):
        return getattr(subprocess, name)
    def run(self, command, **kwargs):
        out = Path(command[command.index("--output") + 1]).resolve()
        if not out.is_relative_to(self.root):
            raise ValueError("native child output outside workflow")
        def save(stdout, stderr, return_code, timed_out):
            out.mkdir(parents=True, exist_ok=True)
            for name, value in [("autocell.stdout.log", stdout), ("autocell.stderr.log", stderr)]:
                if isinstance(value, bytes):
                    (out / name).write_bytes(value)
                else:
                    (out / name).write_text(value or "", encoding="utf-8", errors="replace")
            write_json(out / "child-process.json", {"argv":command, "cwd":kwargs.get("cwd"),
                "timeoutSeconds":kwargs.get("timeout"), "returnCode":return_code, "timedOut":timed_out})
        try:
            process = subprocess.run(command, **kwargs)
            save(process.stdout, process.stderr, process.returncode, False)
            return process
        except subprocess.TimeoutExpired as exc:
            save(exc.stdout, exc.stderr, 124, True)
            raise


def normalize_matrix(raw: dict, engine: str | None = None) -> list[dict]:
    if not isinstance(raw, dict) or not raw:
        raise ValueError("aggregate must be a nonempty native cell map")
    rows = []
    for cell, data in raw.items():
        tag(cell)
        if not isinstance(data, dict):
            raise ValueError("invalid native cell aggregate")
        for algorithm, aggregate in data.items():
            if algorithm == "transistors":
                continue
            tag(algorithm)
            if not isinstance(aggregate, dict):
                raise ValueError("invalid algorithm aggregate")
            trials = aggregate.get("trials", [aggregate])
            if not isinstance(trials, list) or any(not isinstance(t, dict) for t in trials):
                raise ValueError("invalid native trial array")
            for index, t in enumerate(trials):
                if type(t.get("success")) is not bool:
                    raise ValueError("native trial must include boolean success")
                exit_code = t.get("return_code")
                if exit_code is not None and type(exit_code) is not int:
                    raise ValueError("invalid process return code")
                timed_out = t.get("timeout", False)
                if type(timed_out) is not bool:
                    raise ValueError("invalid native timeout")
                row_match = re.fullmatch(r"(.+)_r(\d+)", algorithm) if engine == "mr" else None
                rows.append({"cell":cell,"algorithm":algorithm,"trialIndex":index,
                    "requestedAlgorithm":row_match.group(1) if row_match else algorithm,
                    "reportedAlgorithm":t.get("algo_line"),
                    "rowCount":int(row_match.group(2)) if row_match else 1 if engine == "cmos" else None,
                    "nativeSuccess":t["success"],"metricsCollected":t.get("min_cpp") is not None or t.get("cost") is not None,
                    "processExitCode":exit_code,"timedOut":timed_out,
                    "processCompleted":None if exit_code is None else exit_code == 0 and not timed_out,
                    "minCpp":t.get("min_cpp"),"cost":t.get("cost"),"hpwl":t.get("nor_hpwl"),
                    "crossRows":t.get("cross_rows"),"placementMs":t.get("placement_ms"),"wallSeconds":t.get("wall_sec"),
                    "layoutValidity":"NOT_EVALUATED"})
    if not rows:
        raise ValueError("aggregate contains no native trials")
    return rows


def snapshot_inventory(output: Path) -> dict:
    return {"schemaVersion":SNAPSHOT_VERSION,"sourceOutputRoot":str(output.resolve()),
        "files":{str(p.relative_to(output)):digest(p) for p in safe_tree(output) if p != output / "snapshot-files.json"}}


def validate_snapshot(snapshot: Path) -> dict:
    inventory = read_json(snapshot / "snapshot-files.json")
    if not isinstance(inventory, dict) or inventory.get("schemaVersion") != SNAPSHOT_VERSION:
        raise ValueError("unsupported continuation snapshot")
    source = Path(str(inventory.get("sourceOutputRoot", "")))
    if not source.is_absolute() or str(source) == "/":
        raise ValueError("invalid continuation source root")
    files = inventory.get("files")
    if not isinstance(files, dict) or not files:
        raise ValueError("empty continuation inventory")
    actual = {str(p.relative_to(snapshot)) for p in safe_tree(snapshot) if p != snapshot / "snapshot-files.json"}
    if set(files) != actual:
        raise ValueError("continuation inventory file set mismatch")
    for relative, expected in files.items():
        path = confined(snapshot.resolve(), relative)
        if not isinstance(expected, str) or not re.fullmatch("[0-9a-f]{64}", expected) or digest(path) != expected:
            raise ValueError("continuation checksum mismatch: " + relative)
    return inventory


def relocate_json(value: Any, source: Path, destination: Path, *, key="") -> Any:
    # Historical invocations are evidence, never commands to replay.
    if key in {"command", "argv", "cwd"}:
        return value
    if isinstance(value, dict):
        return {k:relocate_json(v,source,destination,key=k) for k,v in value.items()}
    if isinstance(value, list):
        return [relocate_json(v,source,destination,key=key) for v in value]
    if isinstance(value, str) and value.startswith("/") and key in PATH_KEYS:
        path = Path(value)
        if not path.is_relative_to(source):
            raise ValueError("continuation contains external consumed path: " + key)
        relative = path.relative_to(source)
        if ".." in relative.parts:
            raise ValueError("continuation path traversal")
        # Compatibility for the already validated first-version output layout.
        legacy = "_workspace/project/"
        name = relative.as_posix()
        if name == legacy + "config/gf180/config.json":
            relative = Path("inputs/config.json")
        elif name == legacy + "config/gf180/rules_gf180.json":
            relative = Path("inputs/rules.json")
        elif name.startswith(legacy + "input/benchmark/"):
            relative = Path("inputs/netlists") / name.removeprefix(legacy + "input/benchmark/")
        return str(destination / relative)
    return value


def archived_runtime_resource(relative: Path) -> bool:
    # Only the previous adapter's reserved resource directories are omitted.
    # Repeated continuation archives may contain an older original-snapshot.
    parts = relative.parts
    for index in range(len(parts) - 2):
        if parts[index:index+2] == ("_workspace", "project") and parts[index+2] in {"build", "bin", "scripts"}:
            return True
    return False


def archive_snapshot(snapshot: Path, target: Path) -> dict:
    omitted = {}
    target.mkdir(parents=True)
    for path in safe_tree(snapshot):
        relative = path.relative_to(snapshot)
        if archived_runtime_resource(relative):
            omitted[str(relative)] = digest(path)
            continue
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
    return omitted


def continuation(snapshot: Path, output: Path, params: dict, input_hashes: dict,
                 resource_hashes: dict) -> dict:
    inventory = validate_snapshot(snapshot)
    previous = read_json(snapshot / "source-request.json")
    old = validate_request(previous)
    if previous.get("operation") != "known-feasible" or previous.get("engine") != "mr":
        raise ValueError("continuation requires prior MR corpus")
    previous_summary = read_json(snapshot / "summary.json")
    for key in ("scriptSha256", "executableSha256"):
        if previous_summary.get(key) != resource_hashes.get(key):
            raise ValueError("continuation native resources differ: " + key)
    for field in ("cells", "numRows", "tracks", "extraCpp"):
        if old[field] != params[field]:
            raise ValueError("continuation policy differs: " + field)
    for field in ("maxAttempts", "totalTimeoutSeconds", "attemptTimeoutSeconds"):
        if params[field] < old[field]:
            raise ValueError("continuation caps may only increase: " + field)
    previous_lineage = read_json(snapshot / "lineage.json")
    if previous_lineage.get("inputSha256") != input_hashes:
        raise ValueError("continuation config/rules/netlist identity differs")
    omitted = archive_snapshot(snapshot, output / "original-snapshot")
    source = Path(inventory["sourceOutputRoot"])
    shutil.copytree(snapshot / "native", output / "native")
    derived = {}
    for path in (output / "native").rglob("*.json"):
        original = read_json(path)
        relocated = relocate_json(original, source, output)
        if relocated != original:
            before = digest(path)
            write_json(path, relocated)
            derived[str(path.relative_to(output))] = {"sourceSha256":before,"derivedSha256":digest(path)}
    return {"sourceOutputRoot":str(source),"snapshotInventorySha256":digest(snapshot / "snapshot-files.json"),
            "originalSnapshotPath":"original-snapshot","relocatedNativePath":"native","derivedJsonSha256":derived,
            "omittedRuntimeResourceSha256":omitted,"nativeResourceIdentityVerified":True,
            "sourceWrapperSha256":previous_summary.get("wrapperSha256"),"currentWrapperSha256":digest(Path(__file__)),
            "policy":"consumed paths relocated; historical argv/cwd retained; original evidence and cumulative attempts/time preserved"}


def copy_input(root: Path, relative: str, target: Path, hashes: dict, key: str) -> Path:
    source = confined(root, relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    hashes[key] = digest(source)
    return target


def trusted_project(request: dict) -> tuple[Path, Path | None]:
    resources = request.get("trustedResources")
    if not isinstance(resources, dict):
        raise ValueError("missing service-generated trusted resources")
    native_root = Path(str(resources.get("nativeRoot", "")))
    executable = None if request["operation"] == "algorithm-report" else Path(str(resources.get("executable", "")))
    if not native_root.is_absolute() or executable is not None and not executable.is_absolute():
        raise ValueError("trusted resource bindings must be absolute")
    project_name = "autocellgen-MR" if request["engine"] == "mr" else "autocellgen-cmos"
    project = native_root if native_root.name == project_name else native_root / "proj" / project_name
    if not (project / "scripts/benchmark_report.py").is_file() or executable is not None and not executable.is_file():
        raise ValueError("trusted native workflow resources missing")
    expected = resources.get("executableSha256")
    if executable is not None and (not isinstance(expected, str) or digest(executable) != expected):
        raise ValueError("trusted executable checksum differs")
    return project.resolve(), executable.resolve() if executable is not None else None


def stage_resources(project: Path, executable: Path | None, workspace: Path, operation: str) -> dict:
    workspace.mkdir(parents=True)
    scripts = ["benchmark_report.py"]
    if operation == "algorithm-matrix":
        scripts.append("benchmark_runner.py")
    if operation == "known-feasible":
        scripts.append("build_known_feasible_corpus.py")
    scripts += [name for name in ("ascii_to_gds_gdstk.py", "gds_merge_all_layers_klayout.rb") if (project / "scripts" / name).is_file()]
    hashes = {}
    for name in scripts:
        source, target = project / "scripts" / name, workspace / "scripts" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        hashes[name] = digest(source)
    if executable is not None:
        (workspace / "build/bin").mkdir(parents=True)
        target = workspace / "build/bin/autocell"
        shutil.copy2(executable, target)
        target.chmod(target.stat().st_mode | 0o100)
    for ancestor in ([] if operation == "algorithm-report" else [project, *project.parents]):
        jar = ancestor / "bin/ascii2gdsii.jar"
        if jar.is_file():
            (workspace / "bin").mkdir(exist_ok=True)
            shutil.copyfile(jar, workspace / "bin/ascii2gdsii.jar")
            hashes["ascii2gdsii.jar"] = digest(jar)
            break
    return hashes


def captured_main(module, argv: list[str], output: Path, prefix: str) -> int:
    stdout, stderr = io.StringIO(), io.StringIO()
    try:
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = module.main(argv)
    finally:
        (output / f"{prefix}.stdout.log").write_text(stdout.getvalue(), encoding="utf-8")
        (output / f"{prefix}.stderr.log").write_text(stderr.getvalue(), encoding="utf-8")
    return int(code or 0)


def run(request_path: Path, output: Path, artifacts_root: Path) -> dict:
    root = artifacts_root.resolve()
    if not request_path.resolve().is_relative_to(root):
        raise ValueError("request outside job")
    request = read_json(request_path)
    params = validate_request(request)
    project, executable = trusted_project(request)
    if output.is_symlink() or output.exists() and any(output.iterdir()):
        raise ValueError("workflow output must be fresh and empty")
    output = output.resolve()
    if not output.is_relative_to(root) or output == root:
        raise ValueError("workflow output outside job")
    output.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(request_path, output / "source-request.json")
    operation = request["operation"]
    runtime_id = hashlib.sha256(str(output).encode("utf-8")).hexdigest()[:16]
    workspace = root / "work/native" / runtime_id / "project"
    if workspace.exists():
        raise ValueError("runtime workspace must be fresh")
    scripts = stage_resources(project, executable, workspace, operation)
    inputs, input_hashes = request.get("inputs", {}), {}
    if not isinstance(inputs, dict):
        raise ValueError("inputs must be an object")
    netlists = inputs.get("netlists", {})
    netdir = output / "inputs/netlists"
    for cell in params.get("cells", []):
        relative = netlists.get(cell)
        if relative is None:
            raise ValueError("exactly one staged netlist required: " + cell)
        copy_input(root, relative, netdir / f"{cell}.sp", input_hashes, "netlist:" + cell)
    if set(netlists) != set(params.get("cells", [])):
        raise ValueError("unexpected staged netlist cell")
    native = output / "native"
    lineage = {"schemaVersion":"acg.research-lineage.v1","inputSha256":input_hashes,
               "parentResultId":request.get("sourceResultId") or params.get("sourceResultId") or params.get("resumeResultId")}
    return_code = 0
    summary = {"schemaVersion":VERSION,"operation":operation,"engine":request["engine"],
        "parameters":params,"budget":request.get("budget", {}),"processCompleted":True,
        "foundryCertification":False,"lvs1Certification":False,"scriptSha256":scripts,
        "wrapperSha256":digest(Path(__file__)),"executableSha256":digest(executable) if executable is not None else None,
        "rawReportPaths":[],"warnings":[]}
    if operation in {"algorithm-matrix", "algorithm-report"}:
        report = load_module(workspace / "scripts/benchmark_report.py", "acg_native_report")
        if operation == "algorithm-matrix":
            native.mkdir()
            configs = inputs.get("configs", {})
            if set(configs) != set(params["algorithms"]):
                raise ValueError("exactly one config required per algorithm")
            configdir = output / "inputs/configs"
            for algo in params["algorithms"]:
                config = copy_input(root, configs[algo], configdir / f"{algo}.json", input_hashes, "config:"+algo)
                if request["engine"] == "mr" and 1 in params["rowCounts"] and read_json(config).get("num_rows", 1) != 1:
                    raise ValueError("native row-count 1 reuses base config; base num_rows must equal 1")
            rules = copy_input(root, inputs.get("rules"), output / "inputs/rules.json", input_hashes, "rules")
            runner = load_module(workspace / "scripts/benchmark_runner.py", "acg_native_runner")
            runner.REPO_ROOT, runner.AUTOCELL = workspace, workspace / "build/bin/autocell"
            runner.CONFIG_DIR, runner.RULES = output / "inputs", rules
            runner.NETLIST_DIR, runner.OUTPUT_DIR = netdir, native
            runner.subprocess = ObservedSubprocess(native)
            argv = ["--cells",",".join(params["cells"]),"--algos",",".join(params["algorithms"]),
                    "--algo-dir",str(configdir),"--threads",str(params["threads"]),"--trials",str(params["trials"]),
                    "--output",str(output / "aggregate.json")]
            if request["engine"] == "mr":
                argv += ["--num-rows",",".join(map(str, params["rowCounts"]))]
            return_code = captured_main(runner, argv, output, "runner")
        else:
            copy_input(root, inputs.get("aggregate"), output / "aggregate.json", input_hashes, "aggregate")
        raw = read_json(output / "aggregate.json")
        summary["metrics"] = normalize_matrix(raw, request["engine"])
        report_code = captured_main(report, ["--input",str(output / "aggregate.json"),"--output",str(output / "REPORT.md"),
                                            "--max-cols",str(params["maxCols"])], output, "report")
        if report_code:
            raise ValueError("native report failed")
        summary["rawReportPaths"] = ["aggregate.json", "REPORT.md"]
        summary["warnings"] = ["Native success means metrics collected and may include timeout/nonzero exits; layout validity is not evaluated.",
                               "Markdown is the unchanged native report, including its original baseline headings and static narrative."]
        with (output / "metrics.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(summary["metrics"][0]))
            writer.writeheader(); writer.writerows(summary["metrics"])
    else:
        base = copy_input(root, inputs.get("configBase"), output / "inputs/config.json", input_hashes, "configBase")
        rules = copy_input(root, inputs.get("rules"), output / "inputs/rules.json", input_hashes, "rules")
        if str(read_json(base).get("tech", "")).lower() != "gf180":
            raise ValueError("known-feasible requires GF180 config")
        resume = inputs.get("resume")
        if resume:
            lineage["continuation"] = continuation(confined(root, resume, directory=True), output, params, input_hashes,
                                                        {"scriptSha256":scripts,"executableSha256":summary["executableSha256"]})
        else:
            native.mkdir()
        corpus = load_module(workspace / "scripts/build_known_feasible_corpus.py", "acg_native_corpus")
        corpus.PROJECT = workspace
        corpus.subprocess = ObservedSubprocess(native)
        return_code = captured_main(corpus, ["--cells",",".join(params["cells"]),"--netlist-dir",str(netdir),
            "--output",str(native),"--config-base",str(base),"--rules",str(rules),"--autocell",str(workspace / "build/bin/autocell"),
            "--tracks",",".join(map(str,params["tracks"])),"--num-rows",str(params["numRows"]),
            "--extras",",".join(map(str,params["extraCpp"])),"--max-attempts",str(params["maxAttempts"]),
            "--total-timeout",str(params["totalTimeoutSeconds"]),"--attempt-timeout",str(params["attemptTimeoutSeconds"])], output, "corpus")
        summary["cells"] = []
        for cell in params["cells"]:
            path = native / cell / "manifest.json"
            if not path.is_file():
                raise ValueError("native corpus missing cell manifest")
            manifest = read_json(path)
            witness = manifest.get("witness")
            witness_relative = None
            if witness:
                witness_path = Path(witness)
                if not witness_path.resolve().is_relative_to(output):
                    raise ValueError("native witness outside job")
                witness_relative = str(witness_path.relative_to(output))
            summary["cells"].append({"cell":cell,"status":manifest.get("status"),"terminationReason":manifest.get("termination_reason"),
                "attemptCount":len(manifest.get("attempts", [])),"consumedSeconds":sum(t.get("wall_time_sec",0) for t in manifest.get("attempts",[])),
                "manifestPath":str(path.relative_to(output)),"witnessPath":witness_relative,
                "validationLevel":"MODEL_PLACEMENT_ROUTED_GDS_LVS0" if manifest.get("status") == "RESEARCH_GDS_VALID" else "NOT_ESTABLISHED",
                "lvs1":"NOT_RUN","foundrySignoff":"NOT_RUN"})
        summary["rawReportPaths"] = ["native/index.json"] + [x["manifestPath"] for x in summary["cells"]]
        summary["warnings"] = ["RESEARCH_GDS_VALID certifies native model/placement/routed-GDS and LVS0 witness only; LVS1 and foundry signoff are not run.",
                               "Search caps, native portfolio, seeds, timeouts and resumable consumed attempts/time are preserved."]
        with (output / "corpus.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(summary["cells"][0]))
            writer.writeheader(); writer.writerows(summary["cells"])
    lineage["inputSha256"] = input_hashes
    write_json(output / "lineage.json", lineage)
    summary["nativeReturnCode"] = return_code
    has_incomplete_trials = any(t["processCompleted"] is not True for t in summary.get("metrics", []))
    summary["status"] = "completed" if return_code == 0 and not has_incomplete_trials else "partial"
    summary["evidenceSha256"] = {str(p.relative_to(output)):digest(p) for p in safe_tree(output) if "original-snapshot" not in p.relative_to(output).parts}
    write_json(output / "summary.json", summary)
    write_json(output / "snapshot-files.json", snapshot_inventory(output))
    return summary


