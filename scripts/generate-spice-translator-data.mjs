#!/usr/bin/env node
/**
 * generate-spice-translator-data.mjs — V3
 * Indexes docs/finalbatchrun2 + output/** for plot images.
 * Three result levels: Full Batch, PDK+Source→Target, Translation File.
 */
import { readFileSync, readdirSync, statSync, copyFileSync, existsSync, mkdirSync, writeFileSync } from "fs";
import { resolve, basename, extname, join } from "path";
import { createHash } from "crypto";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ROOT = resolve(__dirname, "..");
const PUBLIC_DIR = resolve(ROOT, "public/translator");
const OUT_FILE = resolve(ROOT, "src/data/generatedSpiceTranslatorManifest.ts");
const JSON_FILE = resolve(ROOT, "src/data/generatedSpiceTranslatorManifest.json");

const SOURCE_PRIORITY = [process.env.TRANSLATOR_SOURCE, resolve(ROOT,"external","new-spice-translator"), resolve(ROOT,"..","new-spice-translator")].filter(Boolean);
let SOURCE_DIR = null;
for (const p of SOURCE_PRIORITY) { if (existsSync(resolve(p,"docs","finalbatchrun2"))) { SOURCE_DIR = p; break; } }
if (!SOURCE_DIR) { console.error("No new-spice-translator source found"); process.exit(1); }

const FINAL_DIR = resolve(SOURCE_DIR, "docs/finalbatchrun2");
const OUTPUT_DIR = resolve(SOURCE_DIR, "output");
const EXCLUDE = ["private-models","private_models"];

function isExcluded(s) { return EXCLUDE.some(t => s.includes(t)); }
function fileHash(p) { try { return createHash("md5").update(readFileSync(p)).digest("hex").slice(0,8); } catch { return "unknown"; } }
function fmtSize(b) { return b<1024?`${b} B`:`${(b/1024).toFixed(1)} KB`; }
function copyPublic(src, subdir) {
  const d = resolve(PUBLIC_DIR, subdir); mkdirSync(d,{recursive:true});
  const n = `${basename(src, extname(src))}_${fileHash(src)}${extname(src)}`;
  try { copyFileSync(src, resolve(d, n)); return `translator/${subdir}/${n}`; } catch { return null; }
}
function probePng(fp) {
  try { const b = readFileSync(fp); if (b[0]!==0x89||b[1]!==0x50) return null; const w=b.readUInt32BE(16),h=b.readUInt32BE(20); return {width:w,height:h,aspectRatio:+(w/h).toFixed(3)}; } catch { return null; }
}
function parseCsv(txt) {
  const lines = txt.trim().split(/\r?\n/).filter(Boolean);
  if (lines.length<2) return {columns:[],rows:[]};
  const headers = lines[0].split(",").map(h=>h.trim());
  return {columns:headers, rows:lines.slice(1).map(l=>{const v=l.split(","); const o={}; headers.forEach((h,i)=>o[h]=v[i]?.trim()??""); return o;})};
}
function extractHero(md) {
  const n={}; const m=(re,k)=>{const x=md.match(re); if(x)n[k]=x[1].trim();};
  m(/files discovered:\s*\*?\*?(\d+)/i,"sourceFiles"); m(/Successful translations:\s*\*?\*?(\d+)/i,"successfulTranslations");
  m(/Models translated:\s*\*?\*?([\d,]+)/i,"modelsTranslated"); m(/Verification result:\s*\*?\*?(\d+)\/(\d+)/i,"verification");
  m(/Round-trip consistency:\s*\*?\*?(\d+)\/(\d+)/i,"roundTrip"); m(/Monte Carlo stability:\s*\*?\*?(\d+)\/(\d+)/i,"monteCarlo");
  return n;
}

/** Build semantic caption from filename */
function plotCaption(name, pdk) {
  const n = name.toLowerCase();
  if (n.includes("verification_summary")) return {title:"Verification Summary",what:"Overview of all verification checks for this result.",why:"Confirms translation correctness across DC, AC, transient, and noise domains.",device:"—",plotType:"verification_summary"};
  if (n.includes("idvgs")) return {title:"Id–Vgs Transfer Characteristic",what:"Gate voltage vs drain current transfer curve.",why:"Validates threshold voltage and transconductance matching after translation.",device:name.split("_")[0]?.replace(/[^a-zA-Z0-9]/g,"")||"MOS",plotType:"idvgs"};
  if (n.includes("idvds")) return {title:"Id–Vds Output Characteristic",what:"Drain voltage vs drain current at multiple gate bias points.",why:"Verifies output conductance and saturation region accuracy.",device:name.split("_")[0]?.replace(/[^a-zA-Z0-9]/g,"")||"MOS",plotType:"idvds"};
  if (n.includes("gummel")) return {title:"Gummel Plot",what:"Collector and base current vs base-emitter voltage for BJT devices.",why:"Validates current gain (beta) and junction characteristics after translation.",device:name.split("_")[0]?.replace(/[^a-zA-Z0-9]/g,"")||"BJT",plotType:"gummel"};
  return {title:name.replace(/_[a-f0-9]{8}\.(png|svg)$/i,"").replace(/[_-]/g," "),what:"Original verification output generated by the tool.",why:"Part of the automated translation verification pipeline.",device:"—",plotType:"other"};
}

function main() {
  console.log(`[generate-spice-translator-data] source: ${SOURCE_DIR}`);
  const allMd=[], allJson=[], allCsv=[], allTex=[], allOther=[];

  const idxDir = (dir, prefix="") => {
    if (!existsSync(dir)) return;
    for (const e of readdirSync(dir)) {
      const fp = resolve(dir,e); if (isExcluded(fp)) continue;
      let st; try { st=statSync(fp); } catch { continue; }
      if (st.isDirectory()) { idxDir(fp, prefix+e+"/"); continue; }
      const ext = extname(e).toLowerCase(), rp = prefix+e, sz = fmtSize(st.size), h = fileHash(fp);
      if (ext===".md") { allMd.push({name:e,relPath:rp,size:sz,hash:h,fetchUrl:copyPublic(fp,"reports"),content:readFileSync(fp,"utf-8")}); }
      else if (ext===".json") { let p=null; try{p=JSON.parse(readFileSync(fp,"utf-8"));}catch{} allJson.push({name:e,relPath:rp,size:sz,hash:h,parsed:p}); }
      else if (ext===".csv") { allCsv.push({name:e,relPath:rp,size:sz,hash:h,...parseCsv(readFileSync(fp,"utf-8"))}); }
      else if (ext===".tex") { allTex.push({name:e,relPath:rp,size:sz,hash:h,format:"tex"}); }
      else { allOther.push({name:e,relPath:rp,size:sz,hash:h,format:ext||"unknown"}); }
    }
  };
  idxDir(FINAL_DIR);

  // Index output/ plots
  const allOutputPlots = [];
  const outputPlotsByScope = {}; // scope → plots[]
  if (existsSync(OUTPUT_DIR)) {
    const scan = (dir, scope="") => {
      for (const e of readdirSync(dir)) {
        const fp = resolve(dir,e); if (isExcluded(fp)) continue;
        let st; try { st=statSync(fp); } catch { continue; }
        if (st.isDirectory()) {
          const newScope = scope || e; scan(fp, newScope);
          continue;
        }
        const ext = extname(e).toLowerCase();
        if (ext===".png"||ext===".svg") {
          const displayUrl = copyPublic(fp,"plots");
          const dims = ext===".png"?probePng(fp):null;
          const s = scope || "_root";
          if (!outputPlotsByScope[s]) outputPlotsByScope[s]=[];
          const plot = {name:e,relPath:e,format:ext.slice(1),size:fmtSize(st.size),hash:fileHash(fp),displayUrl,scope:s,...(dims||{}),caption:plotCaption(e,s)};
          outputPlotsByScope[s].push(plot);
          allOutputPlots.push(plot);
        }
      }
    };
    scan(OUTPUT_DIR);
  }

  // ─── Build results ───
  const results = [];

  // 1. Full Batch Result
  const batchMd = allMd.find(f=>f.name==="FINALBATCHRUN2.md");
  if (batchMd) {
    const batchHero = extractHero(batchMd.content||"");
    results.push({resultId:"full-batch",title:"Full Batch Translation Result",description:"17 PDKs, full translation and verification pipeline.",kind:"batch",level:0,pdk:"all",sourceFormat:"all",targetFormat:"all",generatedAt:"2026-04-19",status:"completed",
      reports:[{name:batchMd.name,relPath:batchMd.relPath,size:batchMd.size,hash:batchMd.hash,fetchUrl:batchMd.fetchUrl,isOriginal:true}],
      plots:allOutputPlots,
      dataArtifacts:[...allCsv.map(c=>({name:c.name,relPath:c.relPath,format:"csv",size:c.size,hash:c.hash,rows:c.rows,rowCount:c.rows?.length,columns:c.columns})),...allJson.map(j=>({name:j.name,relPath:j.relPath,format:"json",size:j.size,hash:j.hash}))],
      otherArtifacts:[...allTex,...allOther],
      summary:{totalReports:1,totalPlots:allOutputPlots.length,totalData:allCsv.length+allJson.length,hero:{...batchHero,pdks:"17"}},
    });
  }

  // 2. PDK+Source→Target results
  const summaryCsv = allCsv.find(c=>c.name==="pdk_translation_summary.csv");
  const effCsv = allCsv.find(c=>c.name==="pdk_translation_effective_summary.csv");
  if (summaryCsv?.rows) {
    for (const row of summaryCsv.rows) {
      const pdk = row["pdk"]||row["PDK"]||""; const src = row["source_format"]||row["Source"]||""; const tgt = row["target"]||row["Target"]||"";
      if (!pdk) continue;
      const rid = `pdk-${pdk}-${src}-${tgt}`.replace(/[^a-z0-9-]/gi,"_").toLowerCase();
      const scope = `${pdk}_${src}-${tgt}`;
      const scopePlots = outputPlotsByScope[scope]||[];
      const effRow = effCsv?.rows?.find(r=>(r["pdk"]||r["PDK"]||"")===pdk && (r["source_format"]||r["Source"]||"")===src && (r["target"]||r["Target"]||"")===tgt);

      results.push({resultId:rid,title:`${pdk}: ${src} → ${tgt}`,description:`${row["total_files"]||row["Files"]||"?"} files, ${row["successful"]||row["Successful"]||"?"} successful, ${row["success_rate_percent"]||row["Success %"]||"?"}% success, ${row["models_out"]||row["Models Out"]||"?"} models.`,kind:"pdk_target",level:1,pdk,sourceFormat:src,targetFormat:tgt,generatedAt:"2026-04-19",status:parseFloat(row["success_rate_percent"]||row["Success %"]||"0")>=100?"completed":"partial",
        reports:[],
        plots:scopePlots,
        dataArtifacts:[{name:summaryCsv.name,relPath:summaryCsv.relPath,format:"csv",size:summaryCsv.size,hash:summaryCsv.hash,columns:summaryCsv.columns,rowCount:1,rows:[row]}],
        otherArtifacts:[],
        summary:{totalReports:0,totalPlots:scopePlots.length,totalData:1,stats:{files:row["total_files"]||row["Files"]||"?",successful:row["successful"]||row["Successful"]||"?",failed:row["failed"]||row["Failed"]||"?",rawSuccess:row["success_rate_percent"]||row["Success %"]||"?",effectiveSuccess:effRow?.["effective_model_deck_success_percent"]||effRow?.["Effective Model-Deck Success %"]||"?",modelsOut:row["models_out"]||row["Models Out"]||"?",duration:row["total_duration_ms"]||row["Duration (ms)"]||"?",failureReason:row["failure_reason"]||row["Failure Reason"]||"-",notes:row["notes"]||row["Notes"]||""}},
      });
    }
  }

  // 3. File-level results from plot_inventory.csv
  const plotInventoryCsv = allCsv.find(c=>c.name==="plot_inventory.csv");
  if (plotInventoryCsv?.rows) {
    for (const row of plotInventoryCsv.rows) {
      const rid = `file-${(row["plot_file"]||row["Plot File"]||row["filename"]||"").replace(/[^a-z0-9-]/gi,"_").toLowerCase()}`;
      if (!rid||rid==="file-") continue;
      const pdk = row["pdk"]||row["PDK"]||"";
      results.push({resultId:rid,title:row["plot_file"]||row["Plot File"]||row["filename"]||"unknown",description:`Device: ${row["device"]||row["Device"]||"—"} · Type: ${row["plot_type"]||row["Plot Type"]||"—"}`,kind:"pdk_target",level:2,pdk:pdk||"—",sourceFormat:row["source_format"]||row["Source Format"]||"—",targetFormat:row["target_format"]||row["Target Format"]||"—",generatedAt:"2026-04-19",status:"completed",
        reports:[],plots:[],dataArtifacts:[],otherArtifacts:[],
        summary:{totalReports:0,totalPlots:0,totalData:0,stats:{files:"1",successful:"1",rawSuccess:"100",device:row["device"]||row["Device"]||"",plotType:row["plot_type"]||row["Plot Type"]||""}},
      });
    }
  }

  // 4. Unassigned plots → separate result
  const assignedHashes = new Set(results.flatMap(r=>r.plots.map(p=>p.hash)));
  const unassigned = allOutputPlots.filter(p=>!assignedHashes.has(p.hash));
  if (unassigned.length>0) {
    results.push({resultId:"unassigned",title:"Unassigned Artifacts",description:`${unassigned.length} plot(s) that could not be matched to a specific PDK/target scope.`,kind:"unassigned",level:99,pdk:"—",sourceFormat:"—",targetFormat:"—",generatedAt:"",status:"unassigned",reports:[],plots:unassigned,dataArtifacts:[],otherArtifacts:[],summary:{totalReports:0,totalPlots:unassigned.length,totalData:0}});
  }

  const defaultResultId = results[0]?.resultId||"";
  const manifest = {generatedAt:new Date().toISOString(),results,defaultResultId,
    allPdks:[...new Set(results.map(r=>r.pdk).filter(Boolean))],
    allSourceFormats:[...new Set(results.map(r=>r.sourceFormat).filter(Boolean))],
    allTargetFormats:[...new Set(results.map(r=>r.targetFormat).filter(Boolean))],
  };

  // Write — strip rows from dataArtifacts for JSON snapshot
  const slim = {generatedAt:manifest.generatedAt,defaultResultId,allPdks:manifest.allPdks,allSourceFormats:manifest.allSourceFormats,allTargetFormats:manifest.allTargetFormats,
    results:manifest.results.map(r=>({...r,dataArtifacts:r.dataArtifacts.map(d=>({...d,rows:undefined,content:undefined})),reports:r.reports.map(rpt=>({...rpt,content:undefined}))}))
  };
  writeFileSync(JSON_FILE, JSON.stringify(slim,null,2),"utf-8");
  writeFileSync(OUT_FILE, `// Auto-generated: ${new Date().toISOString()}\nimport type { SpiceTranslatorManifest } from "./SpiceTranslatorTypes";\nexport const TRANSLATOR_MANIFEST: SpiceTranslatorManifest = ${JSON.stringify(slim,null,2)};\n`,"utf-8");

  const totalPlots = results.reduce((s,r)=>s+r.plots.length,0);
  console.log(`✅ Results: ${results.length} (batch:${results.filter(r=>r.kind=="batch").length} pdk:${results.filter(r=>r.kind=="pdk_target").length} unassigned:${results.filter(r=>r.kind=="unassigned").length})`);
  console.log(`   Reports: ${allMd.length}, Output plots: ${totalPlots}, CSV: ${allCsv.length}, JSON: ${allJson.length}`);
}
main();
